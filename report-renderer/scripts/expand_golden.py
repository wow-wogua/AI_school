def wave(n, hi, seed, lo=0.0):
    """确定性 21 点波形，值域 [lo, hi]。"""
    return [round(lo + (hi - lo) * (((k * 7 + seed) % 13) + 1) / 14.0, 2) for k in range(n)]


def cum(total, n, wig=0.06, seed=3):
    """确定性累计曲线，末点精确等于 total。"""
    step = float(total) / n
    out, acc = [], 0.0
    for k in range(n):
        acc += step * (1 + wig * (((k + seed) % 5) - 2) / 2.0)
        out.append(round(acc, 1))
    out[-1] = round(float(total), 1)
    return out


def rec(title, subtitle, score, registrants, more=False):
    return {'title': title, 'subtitle': subtitle, 'score': score,
            'registrants': registrants, 'more': more}


